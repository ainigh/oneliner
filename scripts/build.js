#!/usr/bin/env node
/* build: concatenate every src layer, in load order, into dist/weave.js and dist/weave.module.js. */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const sourceDirectory = path.join(root, 'src');
const distDirectory = path.join(root, 'dist');

const files = fs.readdirSync(sourceDirectory).filter(name => name.endsWith('.js')).sort();
const banner = '/* weave.js — built from src/ by scripts/build.js. Do not edit this file. */\n';
const sources = files.map(name => fs.readFileSync(path.join(sourceDirectory, name), 'utf8').trim());
const bundle = banner + sources.join('\n\n') + '\n';

fs.mkdirSync(distDirectory, { recursive: true });
fs.writeFileSync(path.join(distDirectory, 'weave.js'), bundle);

const declaration = /^const Weave = \{\};$/m;
if (!declaration.test(sources[0])) { console.error(`build: ${files[0]} must declare the root, const Weave = {};`); process.exit(1); }
const moduleSources = [sources[0].replace(declaration, 'export const Weave = {};')].concat(sources.slice(1));
const moduleSource = banner + moduleSources.join('\n\n') + '\n\nexport default Weave;\n';
fs.writeFileSync(path.join(distDirectory, 'weave.module.js'), moduleSource);

const size = Buffer.byteLength(bundle);
const budget = 720 * 1024;
const gzippedBudget = 120 * 1024;
const gzipped = require('zlib').gzipSync(bundle).length;
console.log(`weave.js: ${files.length} sources, ${bundle.split('\n').length} lines, ${(size / 1024).toFixed(1)} KB raw, ${(gzipped / 1024).toFixed(1)} KB gzipped (budget ${budget / 1024} KB raw, ${gzippedBudget / 1024} KB gzipped)`);
process.exit(size > budget || gzipped > gzippedBudget ? 1 : 0);
