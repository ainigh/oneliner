#!/usr/bin/env node
/* build: concatenate every src layer, in load order, into dist/weave.js and dist/weave.module.js. */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const sourceDirectory = path.join(root, 'src');
const distDirectory = path.join(root, 'dist');

const files = fs.readdirSync(sourceDirectory).filter(name => name.endsWith('.js')).sort();
const banner = '/* weave.js — built from src/ by scripts/build.js. Do not edit this file. */\n';
const bundle = banner + files.map(name => fs.readFileSync(path.join(sourceDirectory, name), 'utf8').trim()).join('\n\n') + '\n';

fs.mkdirSync(distDirectory, { recursive: true });
fs.writeFileSync(path.join(distDirectory, 'weave.js'), bundle);

const moduleSource = bundle.replace('const Weave = {};', 'export const Weave = {};') + '\nexport default Weave;\n';
fs.writeFileSync(path.join(distDirectory, 'weave.module.js'), moduleSource);

const size = Buffer.byteLength(bundle);
const budget = 384 * 1024;
const gzipped = require('zlib').gzipSync(bundle).length;
console.log(`weave.js: ${files.length} sources, ${bundle.split('\n').length} lines, ${(size / 1024).toFixed(1)} KB raw, ${(gzipped / 1024).toFixed(1)} KB gzipped (budget ${budget / 1024} KB raw)`);
process.exit(size > budget ? 1 : 0);
