/* events: registration, delegation, triggering and the event object readers. */
Weave.library.events = {};
Weave.library.events.registry = Weave.library.composition.weakDictionary();
Weave.library.events.recordsOf = el => Weave.library.control.defaultTo([])(Weave.library.events.registry.get(el));
Weave.library.events.record = (el, entry) => (Weave.library.events.registry.set(el, Weave.library.events.recordsOf(el).concat([entry])), entry);
Weave.library.events.forget = (el, entry) => Weave.library.events.registry.set(el, Weave.library.events.recordsOf(el).filter(row => row !== entry));
Weave.library.events.release = (el, entry) => (Weave.library.browser.removeListener(el, entry.type, entry.handler, entry.options), Weave.library.events.forget(el, entry), undefined);
Weave.library.events.subscribe = (el, entry) => (Weave.library.browser.addListenerWithOptions(el, entry.type, entry.handler, entry.options), () => Weave.library.events.release(el, entry));
Weave.library.events.onWithOptions = (type, handler, options) => el => Weave.library.events.subscribe(el, Weave.library.events.record(el, { type, handler, options }));
Weave.library.events.on = (type, handler) => el => Weave.library.events.onWithOptions(type, handler, undefined)(el);
Weave.library.events.once = (type, handler) => el => Weave.library.events.onWithOptions(type, handler, { once: true })(el);
Weave.library.events.matchingRecords = (el, type, handler) => Weave.library.events.recordsOf(el).filter(entry => Weave.library.control.and(entry.type === type, entry.handler === handler));
Weave.library.events.off = (type, handler) => el => (Weave.library.events.matchingRecords(el, type, handler).forEach(entry => Weave.library.events.release(el, entry)), el);
Weave.library.events.offAll = el => (Weave.library.events.recordsOf(el).forEach(entry => Weave.library.events.release(el, entry)), el);
Weave.library.events.copyListeners = source => target => Weave.library.events.recordsOf(source).reduce((node, entry) => (Weave.library.events.onWithOptions(entry.type, entry.handler, entry.options)(node), node), target);
Weave.library.events.combine = list => () => list.forEach(unsubscribe => unsubscribe());
Weave.library.events.unsubscribeAll = list => list.forEach(unsubscribe => unsubscribe());
Weave.library.events.onAll = obj => el => Weave.library.events.combine(Weave.library.composition.pairs(obj).map(([type, handler]) => Weave.library.events.on(type, handler)(el)));
Weave.library.events.onTypes = (types, handler) => el => Weave.library.events.combine(types.map(type => Weave.library.events.on(type, handler)(el)));
Weave.library.events.targetMatching = selector => event => Weave.library.control.maybe(Weave.library.query.closest(selector))(Weave.library.browser.targetOf(event));
Weave.library.events.matchedTarget = (root, selector, event) => Weave.library.control.guard(matched => Weave.library.predicates.contains(root, matched))(Weave.library.events.targetMatching(selector)(event));
Weave.library.events.delegated = (root, selector, handler) => event => Weave.library.control.maybe(matched => handler(event, matched))(Weave.library.events.matchedTarget(root, selector, event));
Weave.library.events.delegate = (type, selector, handler) => el => Weave.library.events.on(type, Weave.library.events.delegated(el, selector, handler))(el);
Weave.library.events.splitKey = key => Weave.library.composition.words(key);
Weave.library.events.delegateRow = el => ([key, handler]) => Weave.library.events.delegate(Weave.library.composition.first(Weave.library.events.splitKey(key)), Weave.library.composition.rest(Weave.library.events.splitKey(key)).join(Weave.library.browser.keywords.space), handler)(el);
Weave.library.events.delegateAll = obj => el => Weave.library.events.combine(Weave.library.composition.pairs(obj).map(Weave.library.events.delegateRow(el)));
Weave.library.events.trigger = (type, detail) => el => (Weave.library.browser.dispatch(el, Weave.library.browser.createEvent(type, { bubbles: true, cancelable: true, detail })), el);
Weave.library.events.dispatchEvent = event => el => Weave.library.browser.dispatch(el, event);
Weave.library.events.triggerNative = type => el => Weave.library.events.nativeTriggers[type](el);
Weave.library.events.isLoading = () => Weave.library.browser.readyState() === Weave.library.browser.readyStates.loading;
Weave.library.events.ready = f => Weave.library.control.either(Weave.library.events.isLoading, () => Weave.library.events.on(Weave.library.events.types.domContentLoaded, f)(Weave.library.browser.document()), () => Weave.library.timing.defer(f))(f);
Weave.library.events.loaded = f => Weave.library.events.on(Weave.library.events.types.load, f)(Weave.library.browser.window());
Weave.library.events.beforeUnload = f => Weave.library.events.on(Weave.library.events.types.beforeunload, f)(Weave.library.browser.window());
Weave.library.events.withSignal = controller => ({ signal: Weave.library.browser.signalOf(controller) });
Weave.library.events.groupFrom = controller => ({ options: Weave.library.events.withSignal(controller), dispose: () => Weave.library.browser.abort(controller) });
Weave.library.events.group = () => Weave.library.events.groupFrom(Weave.library.browser.createAbortController());
Weave.library.events.hover = (enter, leave) => el => Weave.library.events.onAll({ [Weave.library.events.types.mouseenter]: enter, [Weave.library.events.types.mouseleave]: leave })(el);
Weave.library.events.preventDefault = event => Weave.library.browser.preventDefault(event);
Weave.library.events.stopPropagation = event => Weave.library.browser.stopPropagation(event);
Weave.library.events.stop = event => Weave.library.browser.stopPropagation(Weave.library.browser.preventDefault(event));
Weave.library.events.prevented = handler => event => handler(Weave.library.browser.preventDefault(event));
Weave.library.events.valueOfTarget = event => Weave.library.attributes.value(Weave.library.browser.targetOf(event));
Weave.library.events.onKey = (name, handler) => el => Weave.library.events.on(Weave.library.events.types.keydown, Weave.library.events.keyHandler(name, handler))(el);
Weave.library.events.keyHandler = (name, handler) => event => Weave.library.control.when(Weave.library.predicates.isKey(name), () => handler(event, name))(event);
Weave.library.events.debounced = (ms, handler) => Weave.library.timing.debounce(ms, handler);
Weave.library.events.throttled = (ms, handler) => Weave.library.timing.throttle(ms, handler);

