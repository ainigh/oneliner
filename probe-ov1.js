const { JSDOM } = require('jsdom');
const dom = new JSDOM('<!doctype html><html><body></body></html>', {runScripts:'outside-only', pretendToBeVisual:true});
const w = dom.window, d = w.document;
const W = w.eval(require('fs').readFileSync('dist/weave.js','utf8') + '\nWeave;');
const L = W.library;
const recs = () => L.events.recordsOf(d).length;
const nodes = () => d.querySelectorAll('.weave-overlay-host > *').length;
const st = tag => console.log(tag, JSON.stringify({docListeners:recs(), hostKids:nodes(), lock:L.interaction.scrollLocks.depth, pops:L.overlays.openPopovers.length, bodyKids:d.body.children.length}));
st('baseline');
console.log('== dialog open/close twice ==');
const h = L.overlays.dialog({title:'A', body:[L.elements.div({text:'x'})]});
st('open1');
h.close(); st('close1');
h.close(); st('close2 (idempotent?)');
console.log('== two dialogs, close out of order ==');
const a = L.overlays.dialog({title:'A'});
const b = L.overlays.dialog({title:'B'});
st('two open');
a.close(); st('closed outer first');
b.close(); st('closed inner');
console.log('== popover: anchor removed from DOM ==');
const anchor = L.elements.appendTo(d.body)(L.elements.button({text:'anchor'}));
const p = L.overlays.popover(anchor, {body:[L.elements.div({text:'menu'})]});
st('popover open');
L.elements.remove(anchor);
// now click elsewhere
d.dispatchEvent(new w.Event('pointerdown', {bubbles:true}));
st('after pointerdown with detached anchor');
console.log('== popover open twice (same anchor) ==');
const anchor2 = L.elements.appendTo(d.body)(L.elements.button({text:'a2'}));
const p1 = L.overlays.popover(anchor2, {body:[]});
const p2 = L.overlays.popover(anchor2, {body:[]});
st('two popover opens');
p2.close(); st('closed p2');
p1.close(); st('closed p1 (already closed)');
console.log('== dialog opened from inside a popover ==');
const p3 = L.overlays.popover(anchor2, {body:[]});
const dg = L.overlays.dialog({title:'from popover'});
st('popover + dialog');
dg.close(); st('dialog closed, popover?');
L.overlays.closeAll(); st('closeAll');
